export function getCurrentLanguage() {
  return localStorage.getItem('language') || 'vi';
}

export function setCurrentLanguage(lang) {
  localStorage.setItem('language', lang);
  
  // Dispatch custom event for language change
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

export function t(key, replacements = {}) {
  const lang = getCurrentLanguage();
  let text = translations[lang][key] || translations['vi'][key] || key;
  
  // Replace placeholders like {{count}}, {{found}}, {{total}}
  Object.keys(replacements).forEach(placeholder => {
    const regex = new RegExp(`\\{\\{${placeholder}\\}\\}`, 'g');
    text = text.replace(regex, replacements[placeholder]);
  });
  
  return text;
}

// Get localized game data
export function getLocalizedGameData(game) {
  const lang = getCurrentLanguage();
  
  if (!game) return game;
  
  // Return original if no localization needed
  if (lang === 'vi') return game;
  
  // Create localized copy
  const localized = { ...game };
  
  // Replace with English versions if available
  if (game.name_en) localized.name = game.name_en;
  if (game.description_en) localized.description = game.description_en;
  if (game.gameplay_en) localized.gameplay = game.gameplay_en;
  if (game.tags_en && Array.isArray(game.tags_en)) localized.tags = game.tags_en;
  
  return localized;
}
